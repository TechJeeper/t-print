Import("env")
from pathlib import Path

ROOT = Path(env["PROJECT_DIR"])
DATA = ROOT / "data"
OUT = Path(env["PROJECT_INCLUDE_DIR"]) / "webapp_assets.h"


def c_escape_bytes(data: bytes) -> str:
    parts = []
    for i, b in enumerate(data):
        if i % 24 == 0:
            parts.append("\n  ")
        parts.append(f"0x{b:02x},")
    return "".join(parts)


def as_raw_string(text: str, tag: str) -> str:
    # Prefer C++ raw strings to avoid \x unicode escape issues
    delim = tag
    while f"){delim}\"" in text:
        delim += "x"
    return f'R"{delim}({text}){delim}"'


index = (DATA / "index.html").read_bytes()
app_js = (DATA / "app.js").read_text(encoding="utf-8")
style = (DATA / "style.css").read_text(encoding="utf-8")
icons = (DATA / "icons.js").read_text(encoding="utf-8") if (DATA / "icons.js").exists() else "/* no icons */"
iconify = (
    (DATA / "iconify-icon.min.js").read_text(encoding="utf-8", errors="ignore")
    if (DATA / "iconify-icon.min.js").exists()
    else "/* no iconify */"
)

header = f"""#pragma once
#include <Arduino.h>

// Auto-generated by scripts/embed_webapp.py — do not edit
static const uint8_t WEBAPP_INDEX_HTML[] PROGMEM = {{{c_escape_bytes(index)}
}};
static const size_t WEBAPP_INDEX_HTML_LEN = sizeof(WEBAPP_INDEX_HTML);

static const char WEBAPP_APP_JS[] PROGMEM = {as_raw_string(app_js, "APPJS")};
static const char WEBAPP_STYLE_CSS[] PROGMEM = {as_raw_string(style, "CSS")};
static const char WEBAPP_ICONS_JS[] PROGMEM = {as_raw_string(icons, "ICONS")};
static const char WEBAPP_ICONIFY_JS[] PROGMEM = {as_raw_string(iconify, "ICONIFY")};
"""

OUT.write_text(header, encoding="utf-8")
print(f"Embedded webapp -> {OUT}")
